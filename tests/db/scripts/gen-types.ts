// Usage (from the repository root):
//   pnpm db:types           regenerate packages/database/src/database.types.ts
//   pnpm db:types --check   fail if the committed file differs from the database schema
//
// Reads the schema of the local test database (MADEORA_TEST_DATABASE_URL, default: the database
// `supabase start` runs) with the pinned Supabase CLI, then formats the result with Prettier so the
// committed file is stable. Only a database on this machine is accepted.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { TestDatabaseConfigError, resolveTestDatabaseUrl } from "../src/run-sql.ts";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const typesFile = "packages/database/src/database.types.ts";
const check = process.argv.includes("--check");

function fail(message: string): never {
  console.error(`DB types: ${message}`);
  process.exit(2);
}

let databaseUrl: URL;
try {
  databaseUrl = new URL(resolveTestDatabaseUrl());
} catch (error) {
  if (error instanceof TestDatabaseConfigError) fail(error.message);
  throw error;
}
// Local test databases do not use TLS.
if (!databaseUrl.searchParams.has("sslmode")) databaseUrl.searchParams.set("sslmode", "disable");

const generated = spawnSync(
  "pnpm",
  [
    "exec",
    "supabase",
    "gen",
    "types",
    "typescript",
    "--db-url",
    databaseUrl.href,
    "--schema",
    "public",
  ],
  { cwd: repoRoot, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
);
if (generated.status !== 0) {
  // The CLI's own message, which names the connection problem but not the password.
  const password = databaseUrl.password;
  const stderr = password === "" ? generated.stderr : generated.stderr.replaceAll(password, "***");
  fail(`supabase gen types failed:\n${stderr}`);
}

const formatted = spawnSync("pnpm", ["exec", "prettier", "--stdin-filepath", typesFile], {
  cwd: repoRoot,
  input: generated.stdout,
  encoding: "utf8",
});
if (formatted.status !== 0) fail(`prettier failed:\n${formatted.stderr}`);

const header = "// Generated by `pnpm db:types` from supabase/migrations. Do not edit by hand.\n\n";
const next = header + formatted.stdout;
const path = join(repoRoot, typesFile);

if (check) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // Missing file: reported as out of date below.
  }
  if (current !== next) {
    fail(
      `${typesFile} is out of date. Run \`pnpm db:types\` with the database running and commit it.`,
    );
  }
  console.log(`DB types: ${typesFile} is up to date.`);
} else {
  writeFileSync(path, next);
  console.log(`DB types: wrote ${typesFile}.`);
}
